func TestFindBrowserExecutable(t *testing.T) {
	bin, err := findBrowserExecutable()
	if err != nil {
		t.Logf("No browser found in test environment: %v", err)
		return
	}
	if bin == "" {
		t.Errorf("expected non-empty browser binary path")
	}
	if _, err := os.Stat(bin); err != nil {
		t.Errorf("detected browser binary does not exist on disk: %s", bin)
	}
}

